#!/usr/bin/env bash
# Regenerates App/Wiring/libs_list.gen.bzl from lib_info rules.
# Usage: tools/gen_libs_list.sh [--dry-run]
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=App/Wiring/libs_list.gen.bzl
BAZEL=${BAZEL:-bazelisk}
SCOPE='kind(lib_info, //Features/...)'

q() { "$BAZEL" query --noshow_progress "$1" 2>/dev/null | sort; }

all=$(q "$SCOPE")
dbg=$(q "attr(debug_only, 1, $SCOPE)")
svc=$(q "attr(entry_points, '\[.+\]', $SCOPE)")

gen() {
    cat <<'HDR'
"""
AUTOGENERATED - Do not edit manually!
To update run: 'tools/gen_libs_list.sh'
"""

def lib(label, has_entry_points = False, debug_only = False):
    return struct(label = label, has_entry_points = has_entry_points, debug_only = debug_only)

ALL_LIBS = [
HDR
    for meta in $all; do
        # //Features/LibA:LibA_Info -> //Features/LibA
        label=${meta%%:*}
        has_entry_points=False; grep -qxF "$meta" <<<"$svc" && has_entry_points=True
        extra=""; grep -qxF "$meta" <<<"$dbg" && extra=", debug_only = True"
        echo "    lib(\"$label\", has_entry_points = $has_entry_points$extra),"
    done
    echo "]"
}

new=$(gen)
if [[ "${1:-}" == "--dry-run" ]]; then
    if ! diff -u "$OUT" <(echo "$new") >&2; then echo "$OUT is outdated" >&2; exit 1; fi
    echo "$OUT is up to date"
else
    echo "$new" > "$OUT"
    echo "Wrote $OUT"
fi
